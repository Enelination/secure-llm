def _load_api_keys(raw: str) -> dict:
    keys = {}
    for item in raw.split(","):
        item = item.strip()
        if not item:
            continue
        if ":" in item:
            name, secret = item.split(":", 1)
        else:
            name, secret = item[:6], item
        keys[name.strip()] = hashlib.sha256(secret.strip().encode()).hexdigest()
    return keys


API_KEYS = _load_api_keys(os.getenv("API_KEYS", ""))


class TokenBucket:
    def __init__(self, rate_per_minute: int, burst: int):
        self.capacity = max(1, burst)
        self.refill_per_second = max(rate_per_minute, 1) / 60.0
        self.lock = threading.Lock()
        self.state = {}

    def allow(self, client_id: str) -> bool:
        now = time.monotonic()
        with self.lock:
            tokens, last = self.state.get(client_id, (float(self.capacity), now))
            tokens = min(self.capacity, tokens + (now - last) * self.refill_per_second)
            if tokens < 1.0:
                self.state[client_id] = (tokens, now)
                return False
            self.state[client_id] = (tokens - 1.0, now)
            return True


rate_limiter = TokenBucket(RATE_LIMIT_RPM, RATE_LIMIT_BURST)


def authenticate(
    x_api_key: str = Header(default=None),
    authorization: str = Header(default=None),
) -> str:
    if not REQUIRE_AUTH:
        return "anonymous"

    if not API_KEYS:
        LLM_AUTH_FAILURES_TOTAL.labels(reason="not_configured").inc()
        raise HTTPException(status_code=503, detail="Authentication is not configured")

    provided = x_api_key
    if not provided and authorization and authorization.lower().startswith("bearer "):
        provided = authorization[7:].strip()

    if not provided:
        LLM_AUTH_FAILURES_TOTAL.labels(reason="missing").inc()
        raise HTTPException(
            status_code=401,
            detail="Missing API key",
            headers={"WWW-Authenticate": "Bearer"},
        )

    digest = hashlib.sha256(provided.encode()).hexdigest()
    for name, expected in API_KEYS.items():
        if hmac.compare_digest(digest, expected):
            return name

    LLM_AUTH_FAILURES_TOTAL.labels(reason="invalid").inc()
    raise HTTPException(
        status_code=401,
        detail="Invalid API key",
        headers={"WWW-Authenticate": "Bearer"},
    )


@app.middleware("http")
async def metrics_middleware(request: Request, call_next):
    start = time.perf_counter()

    response = await call_next(request)

    duration = time.perf_counter() - start

    HTTP_REQUESTS_TOTAL.labels(
        method=request.method,
        path=request.url.path,
        status=str(response.status_code),
    ).inc()

    HTTP_REQUEST_DURATION.labels(
        method=request.method,
        path=request.url.path,
    ).observe(duration)

    return response


@app.get("/health")
def health():
    return {"status": "ok"}


@app.get("/ready")
def ready():
    healthy = model_provider.healthy()

    LLM_MODEL_UP.labels(
        provider=MODEL_PROVIDER,
        model=model_provider.name,
    ).set(1 if healthy else 0)

    return {
        "status": "ready" if healthy else "degraded",
        "provider": MODEL_PROVIDER,
        "model": model_provider.name,
        "upstream": healthy,
    }


@app.get("/metrics")
def metrics():
    return Response(
        generate_latest(),
        media_type=CONTENT_TYPE_LATEST,
    )


@app.post("/v1/chat/completions")
def chat(request: ChatRequest, identity: str = Depends(authenticate)):
    if not rate_limiter.allow(identity):
        LLM_RATE_LIMITED_TOTAL.labels(client=identity).inc()
        raise HTTPException(
            status_code=429,
            detail="Rate limit exceeded",
            headers={"Retry-After": "1"},
        )

    start = time.perf_counter()

    LLM_REQUESTS_TOTAL.labels(
        provider=MODEL_PROVIDER,
    ).inc()

    LLM_INFLIGHT_REQUESTS.labels(
        provider=MODEL_PROVIDER,
    ).inc()

    try:
        response = model_provider.generate(request.prompt)

        LLM_REQUEST_DURATION.labels(
            provider=MODEL_PROVIDER,
        ).observe(time.perf_counter() - start)

        model = model_provider.name

        usage = response.get("usage") or {}
        prompt_tokens = usage.get("prompt_tokens", 0) or 0
        completion_tokens = usage.get("completion_tokens", 0) or 0

        if prompt_tokens:
            LLM_PROMPT_TOKENS_TOTAL.labels(
                provider=MODEL_PROVIDER,
                model=model,
            ).inc(prompt_tokens)

        if completion_tokens:
            LLM_COMPLETION_TOKENS_TOTAL.labels(
                provider=MODEL_PROVIDER,
                model=model,
            ).inc(completion_tokens)

        if prompt_tokens or completion_tokens:
            LLM_TOKENS_TOTAL.labels(
                provider=MODEL_PROVIDER,
                model=model,
            ).inc(prompt_tokens + completion_tokens)

        LLM_MODEL_UP.labels(
            provider=MODEL_PROVIDER,
            model=model,
        ).set(1)

        return response

    except Exception:
        LLM_ERRORS_TOTAL.labels(
            provider=MODEL_PROVIDER,
        ).inc()

        LLM_REQUEST_DURATION.labels(
            provider=MODEL_PROVIDER,
        ).observe(time.perf_counter() - start)

        LLM_MODEL_UP.labels(
            provider=MODEL_PROVIDER,
            model=model_provider.name,
        ).set(0)

        raise

    finally:
        LLM_INFLIGHT_REQUESTS.labels(
            provider=MODEL_PROVIDER,
        ).dec()